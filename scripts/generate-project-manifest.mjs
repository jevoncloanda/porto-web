import { mkdir, readdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { compile } from "@mdx-js/mdx";
import matter from "gray-matter";

const root = process.cwd();
const projectsDirectory = path.join(root, "content", "projects");
const outputPath = path.join(root, "src", "generated", "project-sources.ts");
const bodiesDirectory = path.join(root, "src", "generated", "project-bodies");
const bodiesIndexPath = path.join(root, "src", "generated", "project-bodies.ts");

let entries = [];
try {
  entries = await readdir(projectsDirectory, { withFileTypes: true });
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
  console.warn(`[projects] No project content found at ${projectsDirectory}.`);
}

const files = entries
  .filter((entry) => entry.isFile() && entry.name.endsWith(".mdx"))
  .map((entry) => entry.name)
  .sort();

const sources = Object.fromEntries(
  await Promise.all(
    files.map(async (file) => [file, await readFile(path.join(projectsDirectory, file), "utf8")]),
  ),
);

const output = `// Generated by scripts/generate-project-manifest.mjs. Do not edit manually.\n\nexport const projectSources: Readonly<Record<string, string>> = ${JSON.stringify(sources, null, 2)};\n`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, "utf8");

await mkdir(bodiesDirectory, { recursive: true });
const bodyModules = await Promise.all(
  files.map(async (file, index) => {
    const { content } = matter(sources[file]);
    const compiled = await compile(content, { outputFormat: "program" });
    const moduleName = `project-${index}.tsx`;
    await writeFile(
      path.join(bodiesDirectory, moduleName),
      `// Generated by scripts/generate-project-manifest.mjs. Do not edit manually.\n// @ts-nocheck\n/* eslint-disable */\n${compiled}`,
      "utf8",
    );
    return { file, moduleName, index };
  }),
);

for (const entry of await readdir(bodiesDirectory)) {
  if (/^project-\d+\.tsx$/.test(entry) && !bodyModules.some(({ moduleName }) => moduleName === entry)) {
    await unlink(path.join(bodiesDirectory, entry));
  }
}

const imports = bodyModules
  .map(({ index, moduleName }) => `import ProjectBody${index} from "./project-bodies/${moduleName.slice(0, -4)}";`)
  .join("\n");
const bodyEntries = bodyModules
  .map(({ file, index }) => `  ${JSON.stringify(file.slice(0, -4))}: ProjectBody${index},`)
  .join("\n");
await writeFile(
  bodiesIndexPath,
  `// Generated by scripts/generate-project-manifest.mjs. Do not edit manually.\nimport type { ComponentType } from "react";\n${imports}\n\nexport const projectBodies: Readonly<Record<string, ComponentType<{ components?: Record<string, unknown> }>>> = {\n${bodyEntries}\n};\n`,
  "utf8",
);

console.log(`Generated ${path.relative(root, outputPath)} from ${files.length} project files.`);
